/**
 * Export utilities for Admin reports - CSV and PDF generation.
 */

/**
 * Convert array of objects to CSV string and trigger download.
 */
export function exportToCSV(data, filename, columns) {
  if (!data || data.length === 0) return;

  const headers = columns.map((c) => c.label);
  const keys = columns.map((c) => c.key);

  const csvRows = [
    headers.join(','),
    ...data.map((row) =>
      keys.map((key) => {
        let val = row[key] ?? '';
        if (typeof val === 'object' && val?.seconds) {
          val = new Date(val.seconds * 1000).toLocaleDateString();
        }
        val = String(val).replace(/"/g, '""');
        return `"${val}"`;
      }).join(',')
    )
  ];

  const csvString = csvRows.join('\n');
  const blob = new Blob([csvString], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${filename}_${new Date().toISOString().split('T')[0]}.csv`;
  link.click();
  URL.revokeObjectURL(url);
}

/**
 * Generate and trigger a printable PDF-style report using the browser's print dialog.
 */
export function exportToPDF(title, data, columns) {
  if (!data || data.length === 0) return;

  const keys = columns.map((c) => c.key);
  const headers = columns.map((c) => c.label);

  const tableRows = data.map((row) =>
    `<tr>${keys.map((key) => {
      let val = row[key] ?? '';
      if (typeof val === 'object' && val?.seconds) {
        val = new Date(val.seconds * 1000).toLocaleDateString();
      }
      return `<td style="border:1px solid #ddd;padding:8px;">${val}</td>`;
    }).join('')}</tr>`
  ).join('');

  const html = `
    <!DOCTYPE html>
    <html>
    <head>
      <title>${title}</title>
      <style>
        body { font-family: Arial, sans-serif; margin: 40px; color: #333; }
        h1 { color: #0D2D5E; border-bottom: 2px solid #507FD9; padding-bottom: 10px; }
        h2 { color: #507FD9; margin-top: 30px; }
        table { border-collapse: collapse; width: 100%; margin-top: 15px; }
        th { background-color: #507FD9; color: white; padding: 10px; text-align: left; }
        td { border: 1px solid #ddd; padding: 8px; }
        tr:nth-child(even) { background-color: #f9f9f9; }
        .meta { color: #666; font-size: 12px; margin-top: 5px; }
        .footer { margin-top: 30px; border-top: 1px solid #ddd; padding-top: 10px; font-size: 11px; color: #999; }
        @media print { body { margin: 20px; } }
      </style>
    </head>
    <body>
      <h1>Lost & Found Management System</h1>
      <p class="meta">Open University of Sri Lanka</p>
      <h2>${title}</h2>
      <p class="meta">Generated: ${new Date().toLocaleString()} | Total Records: ${data.length}</p>
      <table>
        <thead><tr>${headers.map((h) => `<th>${h}</th>`).join('')}</tr></thead>
        <tbody>${tableRows}</tbody>
      </table>
      <div class="footer">
        <p>This report was automatically generated by the Lost & Found Management System.</p>
      </div>
    </body>
    </html>
  `;

  const printWindow = window.open('', '_blank');
  printWindow.document.write(html);
  printWindow.document.close();
  printWindow.onload = () => {
    printWindow.print();
  };
}

/**
 * Calculate analytics from items data.
 */
export function calculateAnalytics(items, claims) {
  const analytics = {
    byCategory: {},
    byLocation: {},
    byMonth: {},
    byType: { lost: 0, found: 0 },
    byStatus: { open: 0, claimed: 0, resolved: 0 },
    claimStats: { total: 0, pending: 0, approved: 0, denied: 0 },
    recoveryRate: 0,
  };

  items.forEach((item) => {
    // By category
    const cat = item.category || 'unknown';
    analytics.byCategory[cat] = (analytics.byCategory[cat] || 0) + 1;

    // By location
    const loc = item.location || 'unknown';
    analytics.byLocation[loc] = (analytics.byLocation[loc] || 0) + 1;

    // By month
    if (item.date) {
      const month = item.date.substring(0, 7); // YYYY-MM
      analytics.byMonth[month] = (analytics.byMonth[month] || 0) + 1;
    }

    // By type
    if (item.type === 'lost') analytics.byType.lost++;
    else analytics.byType.found++;

    // By status
    const st = item.status || 'open';
    analytics.byStatus[st] = (analytics.byStatus[st] || 0) + 1;
  });

  if (claims) {
    claims.forEach((claim) => {
      analytics.claimStats.total++;
      const st = claim.status || 'pending';
      analytics.claimStats[st] = (analytics.claimStats[st] || 0) + 1;
    });
  }

  const totalItems = items.length || 1;
  analytics.recoveryRate = Math.round(((analytics.byStatus.claimed || 0) / totalItems) * 100);

  return analytics;
}
